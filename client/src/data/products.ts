export function getProductsBySubcategory(slug: string): ProductData[] {
  const slugToSubcategory: Record<string, string> = {
    'leather-jackets': 'Leather Jackets',
    'bomber-jackets': 'Bomber Jackets',
    'suede-jackets': 'Suede Jackets',
    'denim-jackets': 'Denim Jackets',
    'puffer-jackets': 'Puffer Jackets',
    'winter-coats': 'Winter Coats',
    'trench-coats': 'Trench Coats',
    'blazers': 'Blazers',
    'overshirts': 'Overshirts',
    'hooded-jackets': 'Hooded Jackets',
    'varsity-jackets': 'Varsity Jackets',
    'windbreakers': 'Windbreakers',
    'hoodies': 'Hoodies',
    't-shirts': 'T-Shirts',
    'shirts': 'Shirts',
    'pants': 'Pants',
    'belts': 'Belts',
    'wallets': 'Wallets',
    'card-holders': 'Card Holders',
    'gloves': 'Gloves',
    'scarves': 'Scarves',
    'caps': 'Caps',
    'beanies': 'Beanies',
    'sunglasses': 'Sunglasses',
    'watches': 'Watches',
    'hats': 'Hats',
    'keychains': 'Keychains',
    'backpacks': 'Backpacks',
    'messenger-bags': 'Messenger Bags',
    'tote-bags': 'Tote Bags',
    'duffel-bags': 'Duffel Bags',
    'travel-bags': 'Travel Bags',
    'leather-bags': 'Leather Bags',
    'boots': 'Boots',
    'sneakers': 'Sneakers',
    'loafers': 'Loafers',
    'casual-shoes': 'Casual Shoes',
    'formal-shoes': 'Formal Shoes',
  };

  const subcat = slugToSubcategory[slug];
  if (subcat) {
    return allProducts.filter((p) => p.subcategory === subcat);
  }

  if (slug === 'new-arrivals') return allProducts.filter((p) => p.isNew);
  if (slug === 'clothing') return allProducts.filter((p) => p.category === 'Clothing');
  if (slug === 'accessories') return allProducts.filter((p) => p.category === 'Accessories');
  if (slug === 'bags') return allProducts.filter((p) => p.category === 'Bags');
  if (slug === 'shoes') return allProducts.filter((p) => p.category === 'Shoes');
  if (slug === 'sale') return allProducts.filter((p) => p.salePrice);

  if (slug === 'latest-collection') return allProducts.filter((p) => p.isNew).slice(0, 10);
  if (slug === 'trending' || slug === 'trending-now') return [...allProducts].sort((a, b) => b.rating - a.rating).slice(0, 10);
  if (slug === 'best-sellers') return allProducts.filter((p) => p.isBestSeller);
  if (slug === 'limited-edition') return [...allProducts]
    .filter((p) => p.regularPrice >= 500 && (p.isNew || p.isBestSeller))
    .sort((a, b) => b.regularPrice - a.regularPrice)
    .slice(0, 12);
  if (slug === 'seasonal-picks') {
    const seasonalTags = ['winter', 'warm', 'scarf', 'boots', 'coat', 'cashmere', 'shearling', 'parka', 'wool'];
    return allProducts.filter((p) => p.tags.some((tag) => seasonalTags.includes(tag))).slice(0, 12);
  }
  if (slug === 'up-to-20') return allProducts.filter((p) => p.discountPercent && p.discountPercent <= 20);
  if (slug === 'up-to-40') return allProducts.filter((p) => p.discountPercent && p.discountPercent <= 40);
  if (slug === 'up-to-60') return allProducts.filter((p) => p.discountPercent && p.discountPercent <= 60);
  if (slug === 'clearance') return [...allProducts]
    .filter((p) => p.discountPercent && p.discountPercent >= 15)
    .sort((a, b) => (b.discountPercent ?? 0) - (a.discountPercent ?? 0));
  if (slug === 'last-chance') return [...allProducts]
    .filter((p) => p.salePrice && p.stock < 15)
    .sort((a, b) => a.stock - b.stock);

  return [];
}
